export const memoryUiMessages = {
  'zh-CN': zhCN,
  'en-US': enUS,
}

function lookup(messages: Messages, key: string): string | undefined {
  const parts = key.split('.')
  let current: unknown = messages
  for (const part of parts) {
    if (!current || typeof current !== 'object') return undefined
    current = (current as Record<string, unknown>)[part]
  }
  return typeof current === 'string' ? current : undefined
}

export function translate(
  locale: LocaleCode,
  key: string,
  params?: Record<string, string | number>,
): string {
  const value =
    lookup(memoryUiMessages[locale] ?? memoryUiMessages['zh-CN'], key) ??
    lookup(memoryUiMessages['zh-CN'], key) ??
    key
  if (!params) return value
  return value.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  )
}

export function useMessages(locale: MaybeRefOrGetter<LocaleCode>) {
  const currentLocale = computed(() => normalizeLocale(toValue(locale)))
  const t = (key: string, params?: Record<string, string | number>) =>
    translate(currentLocale.value, key, params)
  return { locale: currentLocale, t }
}

export function normalizeLocale(value?: string | null): LocaleCode {
  return value?.toLowerCase().startsWith('en') ? 'en-US' : 'zh-CN'
}
